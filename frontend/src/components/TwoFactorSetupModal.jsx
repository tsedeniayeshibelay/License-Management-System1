import { useState, useEffect } from 'react'
import api from '../services/api'

function TwoFactorSetupModal({ isOpen, onClose, userEmail, onSuccess }) {
  const [step, setStep] = useState(1) // 1: Generate/Scan, 2: Verify
  const [qrCodeUrl, setQrCodeUrl] = useState('')
  const [otp, setOtp] = useState('')
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(false)

  useEffect(() => {
    if (isOpen && step === 1) {
      generate2FA()
    }
  }, [isOpen])

  const generate2FA = async () => {
    try {
      setLoading(true)
      const res = await api.post(`/auth/2fa/generate?email=${encodeURIComponent(userEmail)}`)
      setQrCodeUrl(res.data.qrCodeUrl)
      setError('')
    } catch (err) {
      setError(err.response?.data?.message || 'Failed to generate 2FA QR code')
    } finally {
      setLoading(false)
    }
  }

  const verify2FA = async () => {
    try {
      setLoading(true)
      const res = await api.post(`/auth/2fa/verify?email=${encodeURIComponent(userEmail)}&code=${otp}`)
      if (res.data.message.includes('successfully')) {
        onSuccess()
        onClose()
      } else {
        setError(res.data.message || 'Invalid code')
      }
    } catch (err) {
      setError(err.response?.data?.message || 'Invalid 2FA code')
    } finally {
      setLoading(false)
    }
  }

  if (!isOpen) return null

  return (
    <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-white dark:bg-slate-900 w-full max-w-md rounded-2xl shadow-xl border border-slate-200 dark:border-slate-800 overflow-hidden">
        <div className="p-6">
          <div className="flex justify-between items-center mb-6">
            <h3 className="text-lg font-bold text-slate-900 dark:text-white">Enable 2FA</h3>
            <button onClick={onClose} className="text-slate-400 hover:text-slate-500">
              <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M6 18L18 6M6 6l12 12"></path></svg>
            </button>
          </div>

          {error && (
            <div className="mb-4 p-3 bg-red-50 dark:bg-red-900/20 text-red-600 dark:text-red-400 rounded-lg text-sm font-medium border border-red-200 dark:border-red-800/50">
              {error}
            </div>
          )}

          {step === 1 && (
            <div className="space-y-4 flex flex-col items-center">
              <p className="text-sm text-slate-500 text-center">Scan this QR code with your authenticator app (Google Authenticator, Authy, etc.)</p>
              {loading ? (
                <div className="w-48 h-48 bg-slate-100 dark:bg-slate-800 animate-pulse rounded-lg flex items-center justify-center">
                  <span className="text-slate-400 text-xs">Loading QR...</span>
                </div>
              ) : (
                qrCodeUrl && <img src={qrCodeUrl} alt="2FA QR Code" className="w-48 h-48 rounded-lg shadow-sm border border-slate-200" />
              )}
              <button 
                onClick={() => setStep(2)}
                className="w-full py-2 bg-blue-600 text-white rounded-lg font-bold hover:bg-blue-700 transition-colors"
                disabled={loading || !qrCodeUrl}
              >
                I have scanned the code
              </button>
            </div>
          )}

          {step === 2 && (
            <div className="space-y-4">
              <p className="text-sm text-slate-500 text-center">Enter the 6-digit code generated by your app to verify setup.</p>
              <div>
                <input 
                  type="text" 
                  maxLength="6"
                  placeholder="000000"
                  value={otp}
                  onChange={e => setOtp(e.target.value.replace(/\D/g, ''))}
                  className="w-full px-4 py-3 bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg text-center text-xl font-bold tracking-[0.5em] focus:outline-none focus:ring-2 focus:ring-blue-500"
                />
              </div>
              <div className="flex space-x-3">
                <button 
                  onClick={() => setStep(1)}
                  className="flex-1 py-2 border border-slate-200 dark:border-slate-700 rounded-lg font-bold text-slate-700 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-800 transition-colors"
                >
                  Back
                </button>
                <button 
                  onClick={verify2FA}
                  disabled={loading || otp.length !== 6}
                  className="flex-1 py-2 bg-blue-600 text-white rounded-lg font-bold hover:bg-blue-700 transition-colors disabled:opacity-50"
                >
                  {loading ? 'Verifying...' : 'Verify'}
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  )
}

export default TwoFactorSetupModal
